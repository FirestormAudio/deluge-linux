#!/usr/bin/env bash
# SPDX-License-Identifier: GPL-2.0
#
# Assemble the base bundle: the single artifact the SDK consumes to build app
# images without ever running Buildroot. Runs BOTH profiles, because each ships
# its own rootfs cpio and its own kernel; U-Boot, the DTB and the toolchain are
# config-independent and shared, taken from the last build.
#
# Usage: scripts/mk-bundle.sh <version>
set -euo pipefail

VERSION="${1:?usage: mk-bundle.sh <version>}"
TOP="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$TOP/out"
BR="$TOP/.buildroot"
STAGE="$OUT/deluge-base-$VERSION"

rm -rf "$STAGE"
mkdir -p "$STAGE/boot" "$STAGE/rootfs" "$STAGE/toolchain"

# Each profile's rootfs. `make` leaves out/rootfs.cpio behind each time, so grab
# it before the next profile overwrites it.
#
# Buildroot's output/target/ is incremental — it never removes a previous
# profile's overlay files — so building base then platform in place would leave
# base's /usr/bin/deluge-app (and its runit service) inside platform.cpio. Wipe
# the target tree and the per-package target-install stamps before each profile
# so every cpio contains only its own profile. This re-installs packages (fast,
# no recompilation); the toolchain and kernel in build/ are untouched.
for profile in base platform; do
    echo "=== Building $profile ==="
    rm -rf "$BR/output/target"
    rm -f "$BR"/output/build/*/.stamp_target_installed \
          "$BR"/output/build/*/.stamp_images_installed
    make -C "$TOP" "$profile"
    cp "$OUT/rootfs.cpio" "$STAGE/rootfs/$profile.cpio"
    # Per-profile kernel; U-Boot + DTB are config-independent but copied here so
    # each boot/<profile>/ is self-contained for the packer (elf.pack resolves
    # every segment file from one directory).
    mkdir -p "$STAGE/boot/$profile"
    cp "$OUT/zImage" "$OUT/u-boot.bin" "$OUT/r7s72102-deluge.dtb" "$STAGE/boot/$profile/"
done

# The DTS is identical across profiles, so the compiled DTB must be too. Assert
# it — if this ever fires, the DTB has become profile-dependent and needs the
# same per-profile treatment as zImage.
if ! cmp -s "$STAGE/boot/base/r7s72102-deluge.dtb" "$STAGE/boot/platform/r7s72102-deluge.dtb"; then
    echo "ERROR: base and platform DTBs differ — DTB is no longer profile-independent" >&2
    exit 1
fi

# The memory map ships as the bundle's manifest: same schema, same file.
cp "$TOP/board/synthstrom/deluge/memory-map.json" "$STAGE/manifest.json"

# The app-image packer, shipped so SDKs pack images without cloning this repo:
# the shim + package + the shared memmap/uimage modules it imports flat.
mkdir -p "$STAGE/tools"
cp "$TOP/tools/deluge-mkimage" "$STAGE/tools/"
cp -r "$TOP/tools/deluge_mkimage" "$STAGE/tools/deluge_mkimage"
cp "$TOP/tools/memmap.py" "$TOP/tools/uimage.py" "$STAGE/tools/"
rm -rf "$STAGE/tools/deluge_mkimage/__pycache__"

echo "=== Building the SDK toolchain ==="
make -C "$TOP" sdk
tar -xf "$BR"/output/images/*sdk-buildroot.tar.gz \
    -C "$STAGE/toolchain" --strip-components=1

# Buildroot bakes its build-host path ($BR/output/host) into the SDK's linker
# scripts, .la files and wrappers. Its own relocate-sdk.sh rewrites them to the
# extracted location — without this the toolchain only works on the build host,
# so the bundle (and the DelugeToolchain.cmake below) is not actually portable.
"$STAGE/toolchain/relocate-sdk.sh"

# A relocatable cross-toolchain file, shipped at the bundle root alongside
# manifest.json. It must be self-locating (derive every path from
# CMAKE_CURRENT_LIST_DIR, the directory this file sits in) rather than baking
# in this build host's absolute path, so an external app can do
#   -DCMAKE_TOOLCHAIN_FILE=$DELUGE_BASE/DelugeToolchain.cmake
# no matter where the bundle tarball gets extracted. Same shape as the SDK's
# cmake/DelugeToolchain.cmake.in, just rooted at ${CMAKE_CURRENT_LIST_DIR}
# instead of a substituted @DELUGE_TOOLCHAIN@.
cat > "$STAGE/DelugeToolchain.cmake" <<'EOF'
# Generated by scripts/mk-bundle.sh — do not edit by hand.
#
# Relocatable: every path is derived from CMAKE_CURRENT_LIST_DIR (wherever
# this file — and the bundle it ships in — ends up on disk), not from an
# absolute path baked in at bundle-build time. Point CMake at the sysroot
# and, crucially, at its pkg-config metadata: without PKG_CONFIG_LIBDIR,
# pkg_check_modules(ALSA) silently finds the HOST's alsa and links libdeluge
# against x86 headers.
set(CMAKE_SYSTEM_NAME Linux)
set(CMAKE_SYSTEM_PROCESSOR arm)

set(DELUGE_TOOLCHAIN "${CMAKE_CURRENT_LIST_DIR}/toolchain")
set(CMAKE_SYSROOT "${DELUGE_TOOLCHAIN}/arm-buildroot-linux-musleabihf/sysroot")

set(CMAKE_C_COMPILER   "${DELUGE_TOOLCHAIN}/bin/arm-linux-gcc")
set(CMAKE_CXX_COMPILER "${DELUGE_TOOLCHAIN}/bin/arm-linux-g++")

set(CMAKE_FIND_ROOT_PATH_MODE_PROGRAM NEVER)
set(CMAKE_FIND_ROOT_PATH_MODE_LIBRARY ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_INCLUDE ONLY)
set(CMAKE_FIND_ROOT_PATH_MODE_PACKAGE ONLY)

set(ENV{PKG_CONFIG_SYSROOT_DIR} "${CMAKE_SYSROOT}")
set(ENV{PKG_CONFIG_LIBDIR} "${CMAKE_SYSROOT}/usr/lib/pkgconfig")
EOF

TARBALL="$OUT/deluge-base-$VERSION.tar.zst"
tar --zstd -cf "$TARBALL" -C "$OUT" "deluge-base-$VERSION"
sha256sum "$TARBALL" | awk '{print $1}' > "$TARBALL.sha256"

echo
echo "  Bundle:  $TARBALL"
echo "  SHA256:  $(cat "$TARBALL.sha256")"
echo
echo "  Pin this in the SDK's bundle.lock:"
echo "    version: $VERSION"
echo "    sha256:  $(cat "$TARBALL.sha256")"
