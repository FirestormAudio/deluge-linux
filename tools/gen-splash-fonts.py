#!/usr/bin/env python3
"""Generate C headers for the deluge-splash fonts from deluge-sdk's deluge-fonts.

The Metric font is proprietary (Klim Type Foundry, licensed to Synthstrom); the
Apple II font is the classic 5x7 ROM font. Output is vendored into the splash so
it builds with no network / no SDK dependency. Re-run if the source fonts change.
"""
import argparse, pathlib, re, sys

FONTS = [  # (rust stem, rust const prefix, C prefix, note)
    ("metric_bold_9px", "METRIC_BOLD_9PX", "METRIC9",
     "Metric Bold 9px - PROPRIETARY (Klim Type Foundry, licensed to Synthstrom)."),
    ("font_apple", "FONT_APPLE", "APPLE7",
     "Apple II 7px (5x7) ROM font."),
]

def parse(src_dir, stem, prefix):
    t = (src_dir / f"{stem}.rs").read_text()
    bm = re.search(rf"{prefix}_BITMAP: &\[u8\] = &\[(.*?)\];", t, re.S).group(1)
    data = [int(b, 16) for b in re.findall(r"0x[0-9A-Fa-f]{2}", bm)]
    dblk = re.search(rf"{prefix}_DESCRIPTORS: &\[GlyphDescriptor\] = &\[(.*?)\];", t, re.S).group(1)
    descs = [(int(w), int(o)) for w, o in
             re.findall(r"w_px:\s*(\d+),\s*glyph_index:\s*(\d+)", dblk)]
    height = int(re.search(rf"{prefix}_HEIGHT: u8 = (\d+);", t).group(1))
    return data, descs, height

def emit(cpre, note, data, descs, height):
    L = [f"/* Generated by tools/gen-splash-fonts.py from deluge-sdk deluge-fonts.",
         f"   {note}",
         f"   Do not edit by hand; re-run the generator to update. */",
         f"#ifndef {cpre}_H", f"#define {cpre}_H", '#include "text.h"',
         f"#define {cpre}_HEIGHT {height}", f"#define {cpre}_FIRST 0x20",
         f"#define {cpre}_COUNT {len(descs)}",
         f"static const unsigned char {cpre}_BITMAP[{len(data)}] = {{"]
    for i in range(0, len(data), 12):
        L.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i+12]) + ",")
    L.append("};")
    L.append(f"static const struct glyph {cpre}_GLYPHS[{len(descs)}] = {{")
    for w, o in descs:
        L.append(f"    {{ {w}, {o} }},")
    L += ["};", "#endif", ""]
    return "\n".join(L)

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", default=str(pathlib.Path(__file__).resolve().parents[2] / "deluge-sdk"),
                    help="deluge-sdk checkout (default: a sibling of this repo)")
    ap.add_argument("--out", default="package/deluge-splash/splash/src")
    a = ap.parse_args()
    src = pathlib.Path(a.sdk) / "crates/deluge-fonts/src"
    if not src.is_dir():
        sys.exit(f"deluge-fonts not found at {src}")
    out = pathlib.Path(a.out)
    for stem, rpre, cpre, note in FONTS:
        data, descs, height = parse(src, stem, rpre)
        (out / f"{cpre.lower()}.h").write_text(emit(cpre, note, data, descs, height))
        print(f"wrote {cpre.lower()}.h: {len(data)} bytes, {len(descs)} glyphs, h={height}")

if __name__ == "__main__":
    main()
